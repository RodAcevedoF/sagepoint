import { TokenBalance, User } from '@sagepoint/domain';
import { EnqueueTopicRoadmapUseCase } from '../../../src/features/roadmap/app/usecases/enqueue-topic-roadmap.usecase';
import {
  FakeRoadmapRepository,
  FakeTokenBalanceRepository,
  FakeUserRepository,
} from '../_fakes/repositories';

describe('EnqueueTopicRoadmapUseCase', () => {
  let roadmapRepo: FakeRoadmapRepository;
  let tokenBalanceRepo: FakeTokenBalanceRepository;
  let userRepo: FakeUserRepository;
  let generationQueue: {
    add: jest.Mock;
  };
  let useCase: EnqueueTopicRoadmapUseCase;

  beforeEach(() => {
    roadmapRepo = new FakeRoadmapRepository();
    tokenBalanceRepo = new FakeTokenBalanceRepository();
    userRepo = new FakeUserRepository();
    generationQueue = {
      add: jest.fn().mockResolvedValue(undefined),
    };

    userRepo.seed(User.create('u1', 'test@example.com', 'Test User'));
    tokenBalanceRepo.seed(new TokenBalance('u1', 100));

    useCase = new EnqueueTopicRoadmapUseCase(
      roadmapRepo,
      generationQueue as never,
      tokenBalanceRepo,
      userRepo,
    );
  });

  it('uses the standard autogenerated title for plain topics', async () => {
    const result = await useCase.execute({ topic: 'React', userId: 'u1' });

    expect(result.title).toBe('Learn React');
    expect(generationQueue.add).toHaveBeenCalledWith(
      result.id,
      'React',
      'Learn React',
      'u1',
      undefined,
    );
  });

  it('avoids duplicating Learn when the topic already starts with Learn', async () => {
    const result = await useCase.execute({
      topic: 'Learn React',
      userId: 'u1',
    });

    expect(result.title).toBe('Learn React');
    expect(generationQueue.add).toHaveBeenCalledWith(
      result.id,
      'Learn React',
      'Learn React',
      'u1',
      undefined,
    );
  });

  it('keeps an explicit title unchanged', async () => {
    const result = await useCase.execute({
      topic: 'Learn React',
      title: 'React Fundamentals',
      userId: 'u1',
    });

    expect(result.title).toBe('React Fundamentals');
  });
});
